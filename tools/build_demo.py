"""Build docs/demo.html: the real dashboard (dashboard/*) plus an in-browser stand-in
server (docs/demo-mock.js), in one file that needs no server. Run after changing
the dashboard:  python tools/build_demo.py
"""
import json
import re
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backend import reports  # noqa: E402
from tools.sample_history import history  # noqa: E402

NOT_SERVED_AFTER = 600  # the real default (10 min), so the demo's reports read like a real week


def report_fixtures(floor):
    """Run the real report code on made-up history: tonight (so far) plus 14 past nights."""
    base = date.today()
    ids = [t["id"] for t in floor["tables"]]
    hist = history(ids, nights=15, today=base + timedelta(days=1))  # base-14 .. base
    cutoff = datetime.combine(base, datetime.min.time()).replace(hour=21, minute=30).timestamp()
    hist[base] = [v for v in hist[base] if v["cleared_at"] and v["cleared_at"] < cutoff]  # tonight: so far
    nights = [reports.night(hist[base - timedelta(days=k)], base - timedelta(days=k), floor["tables"], NOT_SERVED_AFTER)
              for k in range(15)]
    return {"base": base.isoformat(), "nights": nights}  # weeks are summed from these in the browser

NOTE = """<div class="demo-note">Demo: a made-up dinner service, sped up. Tables turn red 20 s after guests leave
dishes behind and orange after 30 s with nothing served (real app: 3 and 10 min). Tap them to handle them.</div>
<style>.demo-note { font-size: 13px; color: var(--muted); background: var(--surface-2); border-bottom: 1px solid var(--line);
padding: 6px max(16px, env(safe-area-inset-left, 0px)); line-height: 1.4; }</style>"""


def main():
    html = (ROOT / "dashboard" / "index.html").read_text()
    body = re.search(r"<body>(.*)</body>", html, re.S).group(1)
    body = re.sub(r'\s*<script src="/static/[a-z]+\.js"></script>', "", body)
    css = (ROOT / "dashboard" / "style.css").read_text()
    app = (ROOT / "dashboard" / "app.js").read_text()
    floor = (ROOT / "config" / "floor.json").read_text()
    rep = (ROOT / "dashboard" / "reports.js").read_text()
    fixtures = json.dumps(report_fixtures(json.loads(floor)), separators=(",", ":"))
    mock = (ROOT / "docs" / "demo-mock.js").read_text().replace("/*FLOOR_JSON*/ null", floor.strip()) \
        .replace("/*REPORTS_JSON*/ null", fixtures)
    out = (
        "<title>TableWatch Demo</title>\n"
        "<!-- Generated by tools/build_demo.py from dashboard/ and docs/demo-mock.js. Do not edit by hand. -->\n"
        f"<style>\n{css}</style>\n{NOTE}\n{body}\n<script>\n{mock}</script>\n<script>\n{rep}</script>\n<script>\n{app}</script>\n"
    )
    (ROOT / "docs" / "demo.html").write_text(out)
    print(f"wrote docs/demo.html ({len(out) // 1024} KB)")


if __name__ == "__main__":
    main()
